#!/usr/bin/env python3
"""Regenerate src/icons.js from the npm icon packages.

    python3 tools/build_icons.py        # needs npm and internet
    python3 tools/build.py              # then rebuild index.html

SI = brand glyphs (single 24x24 path + brand hex) from Simple Icons, CC0.
     Some brands were removed from Simple Icons at the owner's request (Microsoft,
     Xbox...); those come from the older snapshot packaged by Iconify (also CC0).
LU = Lucide icon bodies (ISC) for categories and UI.

To add a brand: add its slug to BRANDS (or OLD_BRANDS) with a hex color, run this
script, then reference it as `si: '<slug>'` in CATALOG inside src/app.js.
To add a UI/category icon: add its Lucide name to LUCIDE.
"""
import json, re, subprocess, tarfile, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

BRANDS = ['netflix', 'primevideo', 'movistar', 'spotify', 'applemusic', 'youtube', 'youtubemusic', 'adobe', 'google',
          'icloud', 'apple', 'notion', 'openai', 'claude', 'playstation', 'nintendoswitch', 'vodafone', 'orange', 'dazn',
          'crunchyroll', 'strava', 'duolingo', 'dropbox', 'audible', 'googledrive', 'peloton', 'twitch', 'hbo', 'max']
# slug -> brand hex, taken from the Iconify snapshot (brands no longer in current Simple Icons, or newer ones)
OLD_BRANDS = {'microsoft': '5E5E5E', 'xbox': '107C10', 'googlegemini': '8E75B2', 'amazon': 'FF9900'}
LUCIDE = ['tv', 'music', 'code-xml', 'gamepad-2', 'smartphone', 'dumbbell', 'newspaper', 'cloud', 'heart-pulse', 'bell',
          'triangle-alert', 'upload', 'download', 'sparkles', 'wallet', 'arrow-left-right', 'trash-2', 'plus', 'copy', 'x',
          'shield-check', 'user', 'house', 'briefcase', 'coffee', 'shopping-cart', 'car', 'utensils', 'landmark', 'pencil',
          'check', 'repeat', 'search', 'calendar', 'chart-pie', 'layers', 'clock', 'piggy-bank', 'lightbulb', 'file-text',
          'info', 'sun', 'moon', 'book-open', 'graduation-cap', 'plane', 'shirt', 'gift', 'pill', 'stethoscope', 'baby',
          'dog', 'fuel', 'bus', 'train-front', 'film', 'ticket', 'beer', 'pizza', 'receipt', 'sofa', 'wrench', 'zap', 'wifi',
          'tag', 'star', 'heart', 'palette', 'camera', 'headphones', 'bike', 'droplet', 'flame', 'scissors', 'hammer', 'gem',
          'paw-print', 'car-front', 'cigarette']
PACKAGES = {'si': 'simple-icons@13.21.0', 'lu': 'lucide-static@0.460.0', 'old': '@iconify-json/simple-icons@1.2.10'}


def fetch(pkg, into):
    out = subprocess.run(['npm', 'pack', pkg, '--silent'], cwd=into, check=True, capture_output=True, text=True).stdout.strip().splitlines()[-1]
    dest = into / pkg.replace('/', '_')
    with tarfile.open(into / out) as t:
        t.extractall(dest, filter='data')
    return dest / 'package'


def main():
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        si, lu, old = (fetch(PACKAGES[k], tmp) for k in ('si', 'lu', 'old'))
        data = json.loads((si / '_data' / 'simple-icons.json').read_text())
        data = data['icons'] if isinstance(data, dict) else data
        hexes = {d.get('slug') or re.sub(r'[^a-z0-9]', '', d['title'].lower()): d['hex'] for d in data}
        SI = {}
        for b in BRANDS:
            svg = (si / 'icons' / f'{b}.svg').read_text()
            SI[b] = {'p': re.search(r' d="([^"]+)"', svg).group(1), 'h': hexes.get(b, '000000')}
        old_icons = json.loads((old / 'icons.json').read_text())['icons']
        for b, h in OLD_BRANDS.items():
            SI[b] = {'p': re.search(r' d="([^"]+)"', old_icons[b]['body']).group(1), 'h': h}
        LU = {}
        for n in LUCIDE:
            svg = (lu / 'icons' / f'{n}.svg').read_text()
            LU[n] = re.sub(r'\s+', ' ', re.search(r'<svg[^>]*>(.*)</svg>', svg, re.S).group(1)).strip()
    head = '/* Generated by tools/build_icons.py: SI = Simple Icons paths (CC0), LU = Lucide icon bodies (ISC). Do not edit by hand. */\n'
    (ROOT / 'src' / 'icons.js').write_text(head + 'const SI=' + json.dumps(SI) + ';\nconst LU=' + json.dumps(LU) + ';\n', encoding='utf-8')
    print(f'src/icons.js: {len(SI)} marcas, {len(LU)} iconos')


if __name__ == '__main__':
    main()
